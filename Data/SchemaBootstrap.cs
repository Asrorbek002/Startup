    // Balans tizimi: Shops jadvaliga CreditLimit va NextBillingDate ustunlarini qo'shadi
    // va "BalanceTransactions" (balans tarixi) jadvalini yaratadi. Mavjud ma'lumotga tegmaydi.
    public static void EnsureBalanceSystem(AppDbContext context, ILogger logger)
    {
        try
        {
            var pg = context.Database.IsNpgsql();
            var pk = pg ? @"INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : @"INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT";
            var money = pg ? "NUMERIC(18,2)" : "TEXT";
            var ts = pg ? "TIMESTAMPTZ" : "TEXT";
            var zero = pg ? "0" : "'0'";

            if (pg)
            {
                context.Database.ExecuteSqlRaw($@"ALTER TABLE ""Shops"" ADD COLUMN IF NOT EXISTS ""CreditLimit"" {money} NOT NULL DEFAULT {zero};");
                context.Database.ExecuteSqlRaw($@"ALTER TABLE ""Shops"" ADD COLUMN IF NOT EXISTS ""NextBillingDate"" {ts} NULL;");
            }
            else
            {
                foreach (var sql in new[]
                {
                    $@"ALTER TABLE ""Shops"" ADD COLUMN ""CreditLimit"" {money} NOT NULL DEFAULT {zero};",
                    $@"ALTER TABLE ""Shops"" ADD COLUMN ""NextBillingDate"" {ts} NULL;"
                })
                {
                    try { context.Database.ExecuteSqlRaw(sql); }
                    catch (Exception ex) when (ex.Message.Contains("duplicate column", StringComparison.OrdinalIgnoreCase))
                    {
                        // SQLite: ustun oldindan mavjud, muammo yo'q
                    }
                }
            }

            context.Database.ExecuteSqlRaw($@"CREATE TABLE IF NOT EXISTS ""BalanceTransactions"" (
    ""Id"" {pk},
    ""ShopId"" INTEGER NOT NULL,
    ""Type"" TEXT NOT NULL DEFAULT '',
    ""Amount"" {money} NOT NULL,
    ""BalanceAfter"" {money} NOT NULL,
    ""Note"" TEXT NULL,
    ""CreatedAt"" {ts} NOT NULL
);");
            context.Database.ExecuteSqlRaw(@"CREATE INDEX IF NOT EXISTS ""IX_BalanceTransactions_Shop"" ON ""BalanceTransactions"" (""ShopId"");");

            logger.LogInformation("Balans tizimi (CreditLimit, NextBillingDate, BalanceTransactions) tekshirildi.");
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Balans tizimi jadvallarini yaratishda xatolik.");
        }
    }

