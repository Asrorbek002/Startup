    // "PasswordResetCodes" jadvali: parolni tiklash kodlari (kod hash ko'rinishida saqlanadi).
    public static void EnsurePasswordResetCodes(AppDbContext context, ILogger logger)
    {
        try
        {
            var pg = context.Database.IsNpgsql();
            var pk = pg ? @"INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : @"INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT";
            var ts = pg ? "TIMESTAMPTZ" : "TEXT";
            var boolType = pg ? "BOOLEAN" : "INTEGER";
            var boolFalse = pg ? "FALSE" : "0";

            context.Database.ExecuteSqlRaw($@"CREATE TABLE IF NOT EXISTS ""PasswordResetCodes"" (
    ""Id"" {pk},
    ""ShopId"" INTEGER NOT NULL,
    ""CodeHash"" TEXT NOT NULL DEFAULT '',
    ""ExpiresAt"" {ts} NOT NULL,
    ""Attempts"" INTEGER NOT NULL DEFAULT 0,
    ""Used"" {boolType} NOT NULL DEFAULT {boolFalse},
    ""ResetTokenHash"" TEXT NULL,
    ""ResetTokenExpiresAt"" {ts} NULL,
    ""CreatedAt"" {ts} NOT NULL,
    ""IpAddress"" TEXT NULL
);");
            context.Database.ExecuteSqlRaw(@"CREATE INDEX IF NOT EXISTS ""IX_PasswordResetCodes_Shop"" ON ""PasswordResetCodes"" (""ShopId"");");
            context.Database.ExecuteSqlRaw(@"CREATE INDEX IF NOT EXISTS ""IX_PasswordResetCodes_TokenHash"" ON ""PasswordResetCodes"" (""ResetTokenHash"");");

