    // Buyurtmalar (Orders, OrderPayments) va ta'minotchilar (Suppliers, SupplierPurchases, SupplierPayments)
    // jadvallarini xavfsiz yaratadi. Jadval bor bo'lsa hech narsa qilmaydi, mavjud ma'lumotga tegmaydi.
    public static void EnsureOrdersAndSuppliers(AppDbContext context, ILogger logger)
    {
        try
        {
            var pg = context.Database.IsNpgsql();

            // Turlar: Postgres / SQLite
            var pk = pg ? @"INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : @"INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT";
            var money = pg ? "NUMERIC(18,2)" : "TEXT";
            var qty = pg ? "NUMERIC(18,3)" : "TEXT";
            var ts = pg ? "TIMESTAMPTZ" : "TEXT";

            var statements = new[]
            {
                $@"CREATE TABLE IF NOT EXISTS ""Orders"" (
    ""Id"" {pk},
    ""ShopId"" INTEGER NOT NULL,
    ""CustomerName"" TEXT NOT NULL DEFAULT '',
    ""CustomerPhone"" TEXT NOT NULL DEFAULT '',
    ""Description"" TEXT NULL,
    ""TotalAmount"" {money} NOT NULL,
    ""PaidAmount"" {money} NOT NULL,
    ""Status"" TEXT NOT NULL DEFAULT 'Yangi',
    ""DueDate"" {ts} NULL,
    ""CreatedAt"" {ts} NOT NULL,
    ""DebtorId"" INTEGER NULL,
    ""TransferredAmount"" {money} NOT NULL,
    ""TransferredAt"" {ts} NULL
);",
                @"CREATE INDEX IF NOT EXISTS ""IX_Orders_Shop"" ON ""Orders"" (""ShopId"");",

                $@"CREATE TABLE IF NOT EXISTS ""OrderPayments"" (
    ""Id"" {pk},
    ""OrderId"" INTEGER NOT NULL,
    ""ShopId"" INTEGER NOT NULL,
    ""Amount"" {money} NOT NULL,
    ""PaidAt"" {ts} NOT NULL,
    ""PaidByName"" TEXT NOT NULL DEFAULT '',
    ""Note"" TEXT NULL
);",
                @"CREATE INDEX IF NOT EXISTS ""IX_OrderPayments_Order"" ON ""OrderPayments"" (""OrderId"");",

                $@"CREATE TABLE IF NOT EXISTS ""Suppliers"" (
    ""Id"" {pk},
    ""ShopId"" INTEGER NOT NULL,
    ""Name"" TEXT NOT NULL DEFAULT '',
    ""Phone"" TEXT NOT NULL DEFAULT '',
    ""TotalAmount"" {money} NOT NULL,
    ""PaidAmount"" {money} NOT NULL,
    ""CreatedAt"" {ts} NOT NULL
);",
                @"CREATE INDEX IF NOT EXISTS ""IX_Suppliers_Shop"" ON ""Suppliers"" (""ShopId"");",

                $@"CREATE TABLE IF NOT EXISTS ""SupplierPurchases"" (
    ""Id"" {pk},
    ""SupplierId"" INTEGER NOT NULL,
    ""ShopId"" INTEGER NOT NULL,
    ""ProductId"" INTEGER NULL,
    ""ProductName"" TEXT NOT NULL DEFAULT '',
    ""Unit"" TEXT NOT NULL DEFAULT '',
    ""Quantity"" {qty} NOT NULL,
    ""TotalAmount"" {money} NOT NULL,
    ""PaidAmount"" {money} NOT NULL,
    ""CreatedAt"" {ts} NOT NULL
);",
                @"CREATE INDEX IF NOT EXISTS ""IX_SupplierPurchases_Supplier"" ON ""SupplierPurchases"" (""SupplierId"");",

                $@"CREATE TABLE IF NOT EXISTS ""SupplierPayments"" (
    ""Id"" {pk},
    ""SupplierId"" INTEGER NOT NULL,
    ""ShopId"" INTEGER NOT NULL,
    ""Amount"" {money} NOT NULL,
    ""PaidAt"" {ts} NOT NULL,
    ""Note"" TEXT NULL
);",
                @"CREATE INDEX IF NOT EXISTS ""IX_SupplierPayments_Supplier"" ON ""SupplierPayments"" (""SupplierId"");"
            };

            foreach (var sql in statements)
                context.Database.ExecuteSqlRaw(sql);

            logger.LogInformation("Orders / Suppliers jadvallari tekshirildi.");
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Orders / Suppliers jadvallarini yaratishda xatolik.");
        }
    }

